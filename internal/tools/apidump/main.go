// Command apidump records the public API of this module as text.
//
// It prints one line per exported identifier of every package outside
// internal/ — with the full signature of a function or method, the type of a
// field or variable, and the value of a constant — and writes the lines of
// each package to api/<package>.txt at the module root. Those files are
// committed, so every change to the public API shows up as a diff of them in
// the commit that makes it.
//
//	go run ./internal/tools/apidump          # rewrite api/*.txt
//	go run ./internal/tools/apidump -check   # fail if api/*.txt is stale
//
// The API is read as it is on linux/amd64 without cgo, so the files are the
// same on every machine. Parameter names are part of the report: they are
// what the documentation shows.
package main

//go:generate go run .

import (
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

const (
	// reportDir is where the reports live, relative to the module root.
	reportDir = "api"
	// header is written at the top of every report.
	header = "# Generated by go run ./internal/tools/apidump; review changes like code.\n"
)

var (
	errModule    = errors.New("no go.mod with a module line found")
	errDuplicate = errors.New("two public packages would write the same report")
	errCgo       = errors.New("uses cgo, which apidump does not read")
	errStale     = errors.New("the public API differs from api/*.txt: " +
		"if the change is deliberate, run `go run ./internal/tools/apidump` and commit the result")
)

func main() {
	check := flag.Bool("check", false, "fail, with a diff, if the committed reports differ from the code")
	flag.Parse()
	err := run(*check)
	if err != nil {
		fmt.Fprintln(os.Stderr, "apidump:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	mod, err := findModule()
	if err != nil {
		return err
	}
	reports, leaks, err := buildReports(mod)
	if err != nil {
		return err
	}
	for _, leak := range leaks {
		fmt.Fprintln(os.Stderr, "warning:", leak)
	}
	root, err := os.OpenRoot(mod.dir)
	if err != nil {
		return err
	}
	if check {
		diff, checkErr := checkReports(root, reports)
		fmt.Fprint(os.Stderr, diff)

		return errors.Join(checkErr, root.Close())
	}

	return errors.Join(writeReports(root, reports), root.Close())
}

// module is the Go module the tool runs in.
type module struct {
	dir  string
	path string
}

// findModule returns the module that contains the working directory.
func findModule() (module, error) {
	dir, err := os.Getwd()
	if err != nil {
		return module{}, err
	}
	for {
		modPath, found, readErr := readModulePath(dir)
		switch {
		case readErr != nil:
			return module{}, readErr
		case found:
			return module{dir: dir, path: modPath}, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return module{}, fmt.Errorf("%w above the working directory", errModule)
		}
		dir = parent
	}
}

// readModulePath reads the module path from dir/go.mod, and reports whether
// dir has a go.mod at all.
func readModulePath(dir string) (string, bool, error) {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return "", false, err
	}
	data, readErr := root.ReadFile("go.mod")
	closeErr := root.Close()
	if errors.Is(readErr, fs.ErrNotExist) {
		return "", false, closeErr
	}
	if readErr != nil {
		return "", false, readErr
	}
	for line := range strings.Lines(string(data)) {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), true, closeErr
		}
	}

	return "", false, fmt.Errorf("%w: %s", errModule, dir)
}

// tableDir is the module's package of client versions: over fifteen hundred
// variables, one per version, which would bury every other change in the
// report. Its tests keep the table sound and CI refuses to remove an entry.
const tableDir = "versions"

// publicDirs lists the directories of the module that may hold a public
// package: all of them except internal/, testdata/, the hidden ones and the
// table of client versions.
func publicDirs(dir string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if p != dir && skippedDir(d.Name()) || p == filepath.Join(dir, tableDir) {
			return filepath.SkipDir
		}
		dirs = append(dirs, p)

		return nil
	})

	return dirs, err
}

func skippedDir(name string) bool {
	return name == "internal" || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")
}

// buildReports returns the report of every public package, by file name, and
// the leaks found on the way.
func buildReports(mod module) (map[string]string, []string, error) {
	dirs, err := publicDirs(mod.dir)
	if err != nil {
		return nil, nil, err
	}
	d := newDumper()
	reports := map[string]string{}
	var leaks []string
	for _, dir := range dirs {
		rel, err := filepath.Rel(mod.dir, dir)
		if err != nil {
			return nil, nil, err
		}
		importPath := path.Join(mod.path, filepath.ToSlash(rel))
		api, err := d.dump(dir, importPath)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", importPath, err)
		}
		if api == nil {
			continue
		}
		file := api.pkg.Name() + ".txt"
		if _, dup := reports[file]; dup {
			return nil, nil, fmt.Errorf("%s: another package is named %s: %w", importPath, api.pkg.Name(), errDuplicate)
		}
		leaks = append(leaks, api.leaks...)
		reports[file] = api.text()
	}

	return reports, leaks, nil
}

// packageAPI is the API of one package.
type packageAPI struct {
	pkg   *types.Package
	lines []string
	leaks []string
}

// text is the content of the package's report.
func (a *packageAPI) text() string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "# package %s (import %q)\n", a.pkg.Name(), a.pkg.Path())
	for _, line := range a.lines {
		b.WriteString(line)
		b.WriteByte('\n')
	}

	return b.String()
}

// dumper type-checks packages from source, sharing one importer so that the
// standard library is only read once.
type dumper struct {
	fset     *token.FileSet
	importer types.Importer
	context  build.Context
}

func newDumper() *dumper {
	// The importer reads build.Default, so the platform is pinned there: the
	// reports must not depend on the machine that writes them.
	build.Default.GOOS = "linux"
	build.Default.GOARCH = "amd64"
	build.Default.CgoEnabled = false
	fset := token.NewFileSet()

	return &dumper{fset: fset, importer: importer.ForCompiler(fset, "source", nil), context: build.Default}
}

// dump type-checks the package in dir and renders its API. It returns nil for
// a directory that holds no public Go package.
func (d *dumper) dump(dir, importPath string) (*packageAPI, error) {
	bp, err := d.context.ImportDir(dir, 0)
	if _, noGo := errors.AsType[*build.NoGoError](err); noGo {
		return nil, nil //nolint:nilnil // no package here is not an error
	}
	if err != nil {
		return nil, err
	}
	if bp.Name == "main" {
		return nil, nil //nolint:nilnil // a command has no API to import
	}
	if len(bp.CgoFiles) > 0 {
		return nil, errCgo
	}
	files := make([]*ast.File, 0, len(bp.GoFiles))
	for _, name := range slices.Sorted(slices.Values(bp.GoFiles)) {
		file, parseErr := parser.ParseFile(d.fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if parseErr != nil {
			return nil, parseErr
		}
		files = append(files, file)
	}
	conf := types.Config{Importer: d.importer, Sizes: types.SizesFor("gc", "amd64")}
	pkg, err := conf.Check(importPath, d.fset, files, nil)
	if err != nil {
		return nil, err
	}
	lines, leaks := render(pkg)

	return &packageAPI{pkg: pkg, lines: lines, leaks: leaks}, nil
}

// existingReports lists the reports on disk by file name.
func existingReports(root *os.Root) ([]string, error) {
	paths, err := fs.Glob(root.FS(), reportDir+"/*.txt")
	if err != nil {
		return nil, err
	}
	names := make([]string, len(paths))
	for i, p := range paths {
		names[i] = path.Base(p)
	}

	return names, nil
}

// checkReports compares the reports on disk with the ones the code produces
// and describes what differs. The error is errStale when something does.
func checkReports(root *os.Root, reports map[string]string) (string, error) {
	var out strings.Builder
	for _, file := range slices.Sorted(maps.Keys(reports)) {
		name := path.Join(reportDir, file)
		committed, err := root.ReadFile(name)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			fmt.Fprintf(&out, "%s is missing: a public package has no report\n", name)
		case err != nil:
			return out.String(), err
		case string(committed) != reports[file]:
			out.WriteString(unifiedDiff(name, string(committed), reports[file]))
		}
	}
	existing, err := existingReports(root)
	if err != nil {
		return out.String(), err
	}
	for _, file := range existing {
		if _, ok := reports[file]; !ok {
			fmt.Fprintf(&out, "%s is stale: no public package writes it\n", path.Join(reportDir, file))
		}
	}
	if out.Len() > 0 {
		return out.String(), errStale
	}

	return "", nil
}

// writeReports makes the report directory hold exactly the reports.
func writeReports(root *os.Root, reports map[string]string) error {
	err := root.MkdirAll(reportDir, 0o750)
	if err != nil {
		return err
	}
	existing, err := existingReports(root)
	if err != nil {
		return err
	}
	for _, file := range existing {
		if _, ok := reports[file]; ok {
			continue
		}
		err = root.Remove(path.Join(reportDir, file))
		if err != nil {
			return err
		}
	}
	for file, text := range reports {
		err = root.WriteFile(path.Join(reportDir, file), []byte(text), 0o600)
		if err != nil {
			return err
		}
	}

	return nil
}
